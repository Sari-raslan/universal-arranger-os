import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const files = fs.readdirSync(__dirname).filter(f => fs.statSync(path.join(__dirname,f)).isFile());
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname,'UAOS_TEST_UNVERIFIED_MINIMAL_005_V5_MANIFEST.json'),'utf8'));
const warning = fs.readFileSync(path.join(__dirname,'UAOS_PA3X_RUN_049_DO_NOT_LOAD_WARNING.md'),'utf8');
const sha = crypto.createHash('sha256').update(fs.readFileSync(path.join(__dirname,'UAOS_TEST_UNVERIFIED_MINIMAL_005_V5.PRF'))).digest('hex');
const checks=[]; const check=(name,pass,detail='')=>checks.push({name,pass,detail});
const prfs=files.filter(f=>f.toLowerCase().endsWith('.prf')); const forbidden=files.filter(f=>/\.(set|sty|prs|kst)$/i.test(f));
check('exactly one PRF candidate exists', prfs.length===1 && prfs[0]==='UAOS_TEST_UNVERIFIED_MINIMAL_005_V5.PRF', prfs.join(', '));
check('no SET/STY/PRS/KST exists', forbidden.length===0, forbidden.join(', '));
for (const k of ['keyboardReady','usbWriteApproved','keyboardLoadApproved','packageCopyApproved','fixtureModified','compatibilityClaim','pa3xReadyClaim','usbPathUsed','packagePathUsed','run037CopyScriptExecuted']) check('manifest '+k+' false', manifest[k]===false, String(manifest[k]));
check('testUnverified true', manifest.testUnverified===true, String(manifest.testUnverified));
check('warning says DO NOT LOAD ON PA3X', warning.includes('DO NOT LOAD ON PA3X'));
check('warning says DO NOT COPY TO USB', warning.includes('DO NOT COPY TO USB'));
check('sha256 matches manifest', sha===manifest.sha256, sha);
const result={status:checks.every(c=>c.pass)?'PASS':'FAIL',run:'049',checks,usbWritePerformed:false,packageCopyPerformed:false,keyboardTransferPerformed:false,pa3xLoadPerformed:false,fixtureModified:false,run037CopyScriptExecuted:false};
fs.writeFileSync(path.join(__dirname,'UAOS_PA3X_RUN_049_VALIDATOR_RESULTS.json'), JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
